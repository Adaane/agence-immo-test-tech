import { describe, expect, it } from "vitest";
import { getProperties } from "@/lib/properties/data";
import { loadVisitManifest, visitManifestSchema } from "./manifest";

const frames = (path: string) => ({
  desktop: { path, count: 120, ext: "webp", pad: 4 },
  mobile: { path, count: 120, ext: "webp", pad: 4 },
});

const scene = {
  id: "cour-escalier",
  theme: "light",
  eyebrow: "L'arrivée",
  title: "La cour pavée",
  steps: ["Porche cocher"],
  frames: frames("/scroll-video/paris-8-monceau/cour-escalier/desktop/"),
};

describe("visitManifestSchema", () => {
  it("accepts a manifest generated by the pipeline", () => {
    expect(
      visitManifestSchema.safeParse({ version: 1, fps: 24, scenes: [scene] })
        .success,
    ).toBe(true);
  });

  it("rejects frames served from outside /scroll-video/", () => {
    expect(
      visitManifestSchema.safeParse({
        version: 1,
        fps: 24,
        scenes: [{ ...scene, frames: frames("https://evil.example/") }],
      }).success,
    ).toBe(false);
  });

  it("rejects a visit without scenes", () => {
    expect(
      visitManifestSchema.safeParse({ version: 1, fps: 24, scenes: [] })
        .success,
    ).toBe(false);
  });
});

describe("loadVisitManifest", () => {
  it.each(
    getProperties().flatMap((p) => (p.visit ? [[p.id, p.visit.manifest]] : [])),
  )("loads the three-scene visit of %s", async (_id, manifestUrl) => {
    const manifest = await loadVisitManifest(manifestUrl);
    expect(manifest.scenes).toHaveLength(3);
  });
});
